"""Generates database/sqlserver/01_schema.sql from the SQLAlchemy models using the SQL Server dialect.
Run from the repo root:  python database/generate_sqlserver_schema.py
NOTE: this only COMPILES the DDL for SQL Server; it does not execute it."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from sqlalchemy.dialects import mssql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.database import Base
from app import models  # noqa: F401  (registers tables)

dialect = mssql.dialect()
out = ["-- EventVault schema for Microsoft SQL Server / Azure SQL.",
       "-- GENERATED by database/generate_sqlserver_schema.py from the SQLAlchemy models. Do not edit by hand.",
       "-- Safe to re-run: each table is created only if it does not exist.", ""]
for table in Base.metadata.sorted_tables:
    ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
    out.append(f"IF OBJECT_ID(N'dbo.{table.name}', N'U') IS NULL\nBEGIN\n{ddl};")
    for idx in sorted(table.indexes, key=lambda i: i.name):
        out.append(str(CreateIndex(idx).compile(dialect=dialect)).strip() + ";")
    out.append("END;\nGO\n")
(ROOT / "database/sqlserver/01_schema.sql").write_text("\n".join(out))

from app.db_objects import DEFAULT_CATEGORIES, TRIGGER_MSSQL, VIEW_MSSQL

hdr = "-- GENERATED by database/generate_sqlserver_schema.py from backend/app/db_objects.py. Do not edit by hand.\n"
(ROOT / "database/sqlserver/02_view.sql").write_text(
    hdr + "-- View used by the organizer analytics page (joins events, categories, registrations).\n"
    + VIEW_MSSQL.strip() + ";\nGO\n")
(ROOT / "database/sqlserver/03_trigger.sql").write_text(
    hdr + "-- Trigger: database-level guarantee that an event can never exceed its capacity,\n"
    "-- even if someone writes to the table directly (bypassing the API).\n"
    + TRIGGER_MSSQL.strip() + "\nGO\n")
seed = [hdr + "-- Required lookup data (idempotent). Safe to re-run."]
for r in ("participant", "organizer"):
    seed.append(f"IF NOT EXISTS (SELECT 1 FROM roles WHERE name = N'{r}') INSERT INTO roles (name) VALUES (N'{r}');")
for c in DEFAULT_CATEGORIES:
    seed.append(f"IF NOT EXISTS (SELECT 1 FROM categories WHERE name = N'{c}') INSERT INTO categories (name) VALUES (N'{c}');")
(ROOT / "database/sqlserver/04_seed_lookups.sql").write_text("\n".join(seed) + "\nGO\n")
print("written", len(Base.metadata.sorted_tables), "tables + view + trigger + lookups")
